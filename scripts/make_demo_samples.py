def cjk_page_text(doc: pymupdf.Document, text: str, heading: str | None = None) -> None:
    page = doc.new_page(width=595, height=842)  # A4
    page.insert_font(fontname="cjk", fontbuffer=pymupdf.Font("cjk").buffer)
    y = 72
    if heading:
        page.insert_text((72, y), heading, fontname="cjk", fontsize=16)
        y += 30
    page.insert_textbox(pymupdf.Rect(72, y, 523, 790), text, fontname="cjk", fontsize=11.5, lineheight=1.7)


def make_korean_reading() -> Path:
    doc = pymupdf.open()
    for heading, body in KOREAN_PAGES:
        cjk_page_text(doc, body, heading)
    doc.set_toc([[1, heading, i + 1] for i, (heading, _) in enumerate(KOREAN_PAGES)])
    doc.set_page_labels([{"startpage": 0, "prefix": "", "style": "D", "firstpagenum": 37}])
    doc.set_metadata({"title": "공유 경제 이야기（演示）"})
    doc.subset_fonts()  # 只嵌入用到的字形，文件从 1.7MB 降到几十 KB
    path = OUT / "korean_reading.pdf"
    doc.save(path, garbage=3, deflate=True)
    return path


