def make_vocab_scan() -> Path:
    """用 PIL 画一页 200 DPI 的单词书，再加轻微倾斜、模糊和噪点，模拟扫描件。"""
    fonts = {"ko": ImageFont.truetype("/System/Library/Fonts/AppleSDGothicNeo.ttc", 40),
             "zh": ImageFont.truetype("/System/Library/Fonts/Hiragino Sans GB.ttc", 40)}
    width, height = 1654, 2339  # A4 @ 200 DPI
    img = Image.new("L", (width, height), 250)
    draw = ImageDraw.Draw(img)
    y = 180
    for segments in VOCAB_BOOK:
        x = 160
        for text, lang in segments:
            draw.text((x, y), text, fill=25, font=fonts[lang])
            x += draw.textlength(text, font=fonts[lang])
        y += 78
    img = img.rotate(0.4, fillcolor=250).filter(ImageFilter.GaussianBlur(0.9))
    rnd = random.Random(7)
    noise = Image.effect_noise((width, height), 12).point(lambda v: v - 128 + rnd.randint(-2, 2))
    img = Image.blend(img, Image.merge("L", [noise.point(lambda v: max(0, min(255, 250 + v)))]), 0.15)

    buf = io.BytesIO()
    img.convert("RGB").save(buf, format="JPEG", quality=80)
    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)
    page.insert_image(page.rect, stream=buf.getvalue())
    doc.set_metadata({"title": "TOPIK 中级词汇（演示扫描件）"})
    path = OUT / "vocab_book_scan.pdf"
    doc.save(path, garbage=3, deflate=True)
    return path


